"""Inference and Prediction Pipeline for Deepfake Voice Detection.
Takes preprocessed audio, passes features to the trained CNN,
and returns clear labels, confidence scores, and acoustic interpretations.
"""

import os
from typing import Dict, Any, Union, Optional
import numpy as np
import tensorflow as tf

from src.audio_processor import (
    load_and_preprocess_audio,
    extract_mel_spectrogram,
    extract_mfcc,
    extract_spectral_features,
    AudioValidationError,
    TARGET_SAMPLE_RATE,
    DEFAULT_AUDIO_DURATION
)
from src.model import load_detector_model


class VoiceDetector:
    """End-to-end Voice Deepfake Detector."""

    def __init__(self, model_path: str = "models/deepfake_detector.keras"):
        self.model_path = model_path
        self.model: Optional[tf.keras.Model] = None
        self._load_model()

    def _load_model(self):
        """Loads the trained deep learning model if available."""
        if os.path.exists(self.model_path):
            self.model = load_detector_model(self.model_path)

    @property
    def is_model_loaded(self) -> bool:
        """Returns True only if a real trained model file exists and is loaded."""
        return self.model is not None

    def analyze_audio(
        self,
        file_input: Union[str, bytes, Any],
        filename: str = "audio.wav",
        decision_threshold: float = 0.50
    ) -> Dict[str, Any]:
        """Runs the complete inference workflow on the provided audio input.

        Args:
            file_input: File path, BytesIO, or uploaded file buffer.
            filename: Name of the input audio file.
            decision_threshold: Threshold probability for classifying as FAKE (default 0.50).

        Returns:
            Dict containing prediction label, confidence, raw score, acoustic features,
            visual data, and metadata.

        Raises:
            AudioValidationError: On invalid or silent audio.
            RuntimeError: If model is not loaded.
        """
        if not self.is_model_loaded:
            raise RuntimeError(
                f"Trained model file not found at '{self.model_path}'. "
                "Please train the model first by running `python train.py`."
            )

        # 1. Preprocess audio
        y_proc, sr, meta = load_and_preprocess_audio(file_input, filename=filename)

        # 2. Extract acoustic features
        mel_tensor = extract_mel_spectrogram(y_proc, sr=sr)
        mfcc_feats = extract_mfcc(y_proc, sr=sr)
        spectral_meta = extract_spectral_features(y_proc, sr=sr)

        # 3. Model Inference (batch dimension: 1, 128, 128, 1)
        input_batch = np.expand_dims(mel_tensor, axis=0)
        raw_output = self.model.predict(input_batch, verbose=0)
        fake_probability = float(raw_output[0][0])

        # 4. Binary Decision and Confidence Calculation
        # Model output represents P(FAKE)
        is_fake = fake_probability >= decision_threshold
        if is_fake:
            prediction_label = "AI-GENERATED / FAKE"
            # Confidence is how sure the model is that it is FAKE
            confidence_pct = round(fake_probability * 100.0, 2)
            risk_level = "High Risk (Synthetic Vocoder Artifacts Detected)" if fake_probability > 0.8 else "Moderate Suspicion"
        else:
            prediction_label = "GENUINE HUMAN VOICE / REAL"
            # Confidence is how sure the model is that it is REAL
            confidence_pct = round((1.0 - fake_probability) * 100.0, 2)
            risk_level = "Low Risk (Natural Vocal Tract Harmonics)"

        # 5. Acoustic Observations & Explanations
        observations = []
        if is_fake:
            observations.append("Aperiodic high-frequency energy distribution typical of neural vocoders.")
            observations.append("Inconsistencies observed across higher Mel-frequency bands.")
            if spectral_meta["mean_spectral_centroid_hz"] > 2500:
                observations.append("Elevated spectral centroid indicative of synthetic over-smoothing or vocoder buzz.")
        else:
            observations.append("Natural formant transitions and dynamic glottal pulse variations detected.")
            observations.append("Consistent biological pitch variations present across speech frames.")
            observations.append("Acoustic harmonics conform to typical human vocal tract acoustics.")

        disclaimer = (
            "Disclaimer: This confidence score is an algorithmic probability generated by a 2D-CNN "
            "analyzing acoustic spectrogram features. It is not an absolute or legally binding guarantee "
            "of authenticity. Acoustic environments, microphone hardware, audio compression (e.g. low-bitrate MP3), "
            "and novel generative AI architectures can influence predictions."
        )

        return {
            "prediction": prediction_label,
            "is_fake": bool(is_fake),
            "confidence": confidence_pct,
            "raw_fake_prob": round(fake_probability, 4),
            "threshold": decision_threshold,
            "risk_level": risk_level,
            "observations": observations,
            "disclaimer": disclaimer,
            "metadata": {**meta, **spectral_meta},
            "audio_signal": y_proc,
            "sample_rate": sr,
            "mel_spectrogram": mel_tensor.squeeze(-1),  # (128, 128)
            "mfcc": mfcc_feats,
        }
